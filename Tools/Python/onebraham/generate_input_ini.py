"""
onebraham.generate_input_ini
============================

Writes the default key bindings into Config/DefaultInput.ini.

WHY BINDINGS LIVE IN AN INI AND NOT ONLY IN THE IMC ASSETS
    Players rebind. When they do, the game has to record their choice somewhere
    that survives a patch, and the only file a shipping build may write is the
    user's config. So the *defaults* are written here into DefaultInput.ini's
    [OneBraham.Input] section, which is shipped, and a player's rebinds are
    written to the same section in GameUserSettings.ini, which overrides it.

    The Enhanced Input mapping contexts still exist and still carry the stick
    dead zones, the modifiers and the triggers - the things that are not a key
    and should not be rebindable. Keys are data. Shape is design.

RUNS OUTSIDE THE EDITOR
    This is pure text: no unreal module, no editor. It can therefore run in CI
    before a build, which is where a bindings regression should be caught.

USAGE
    python3 Tools/Python/onebraham/generate_input_ini.py
"""

from __future__ import print_function

import io
import os

from onebraham import common as C
from onebraham.build_input import ACTIONS, MAPPING_CONTEXTS

INI_PATH = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "Config", "DefaultInput.ini"))

BEGIN_MARKER = "; ==== BEGIN GENERATED [OneBraham.Input] - do not edit by hand ===="
END_MARKER = "; ==== END GENERATED [OneBraham.Input] ===="

# Default gamepad dead zones and sensitivities. These are design values, not
# preferences: a dead zone that is too small makes every pad drift, and a turn
# rate that is too slow makes a shooter unplayable on a controller.
GAMEPAD_DEFAULTS = [
    ("LeftStickDeadZone", 0.18),
    ("RightStickDeadZone", 0.15),
    ("LookSensitivityDefault", 0.045),
    ("LookSensitivityADSMultiplier", 0.72),
    ("LookSensitivityGamepad", 0.055),
    ("LookSensitivityGamepadADSMultiplier", 0.66),
    ("AimAccelerationScale", 0.0),
    ("TurnRateGamepadYaw", 165.0),
    ("TurnRateGamepadPitch", 125.0),
]

# Mouse behaviour: a competitive shooter on PC gets these wrong more often than
# anything else, so they are stated explicitly and shipped as defaults.
MOUSE_DEFAULTS = [
    ("bEnableMouseSmoothing", "False"),
    ("bViewAccelerationEnabled", "False"),
    ("bEnableFOVScaling", "True"),
    ("FOVScale", "1.000000"),
    ("RawMouseInput", "True"),
    ("MouseSensitivityX", "0.045000"),
    ("MouseSensitivityY", "0.045000"),
    ("bScaleMouseByFOV", "False"),
    ("InvertMouseY", "False"),
]


def _key_name(key):
    """Python-side key names to the ini's key names."""
    return key


def build_section():
    lines = []
    lines.append(BEGIN_MARKER)
    lines.append("; Generated by Tools/Python/onebraham/generate_input_ini.py from the")
    lines.append("; ACTIONS table in Tools/Python/onebraham/build_input.py.")
    lines.append(";")
    lines.append("; Format:  +Action=<IA asset name>,<Key>")
    lines.append("; A player's rebind goes in the same section in GameUserSettings.ini")
    lines.append("; and takes precedence over everything below.")
    lines.append("[OneBraham.Input]")

    for _value_type, name, _description, kbm_keys, pad_keys in ACTIONS:
        if not kbm_keys and not pad_keys:
            lines.append(u"; {0}: intentionally unbound - the player picks a key".format(name))
            continue

        for key in kbm_keys:
            lines.append(u"+KeyboardBinding={0},{1}".format(name, _key_name(key)))

        for key in pad_keys:
            lines.append(u"+GamepadBinding={0},{1}".format(name, _key_name(key)))

    lines.append("")
    lines.append("; --- Gamepad shape -------------------------------------------------")
    for name, value in GAMEPAD_DEFAULTS:
        lines.append(u"+GamepadSetting={0}={1}".format(name, value))

    lines.append("")
    lines.append("; --- Mouse ---------------------------------------------------------")
    for name, value in MOUSE_DEFAULTS:
        lines.append(u"+MouseSetting={0}={1}".format(name, value))

    lines.append("")
    lines.append("; --- Contexts, in the order they are applied -----------------------")
    for name, description in MAPPING_CONTEXTS:
        lines.append(u"+MappingContext={0}    ; {1}".format(name, description))

    lines.append("")
    lines.append("; --- Actions by verb (the prompt the HUD shows, per action) -------")
    for _value_type, name, description, _kbm, _pad in ACTIONS:
        lines.append(u"+ActionPrompt={0}={1}".format(name, description))

    lines.append(END_MARKER)
    return u"\n".join(lines)


def write_ini():
    if not os.path.isfile(INI_PATH):
        raise RuntimeError(u"no Config/DefaultInput.ini at {0}".format(INI_PATH))

    with io.open(INI_PATH, "r", encoding="utf-8") as handle:
        text = handle.read()

    section = build_section()

    if BEGIN_MARKER in text and END_MARKER in text:
        begin = text.index(BEGIN_MARKER)
        end = text.index(END_MARKER) + len(END_MARKER)
        text = text[:begin] + section + text[end:]
    else:
        if not text.endswith("\n"):
            text += u"\n"
        text += u"\n" + section + u"\n"

    with io.open(INI_PATH, "w", encoding="utf-8") as handle:
        handle.write(text)

    actions = len(ACTIONS)
    bound = sum(1 for a in ACTIONS if a[3] or a[4])
    print(u"[OB.BUILD] wrote {0} actions ({1} with a default key) to {2}".format(
        actions, bound, INI_PATH))

    return INI_PATH


class _IniReport(object):
    """Same shape as common.BuildReport, so run_all can treat this like any step."""

    def __init__(self, path, actions, bound):
        self.path = path
        self.actions = actions
        self.bound = bound

    def ok(self):
        return self.path is not None

    def summary(self):
        return u"wrote {0} actions ({1} with a default key) to {2}".format(
            self.actions, self.bound, self.path)


def build_all():
    path = write_ini()
    bound = sum(1 for a in ACTIONS if a[3] or a[4])
    return _IniReport(path, len(ACTIONS), bound)


def main():
    build_all()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
